// Default icon to use when an unknown icon key is provided
export const DEFAULT_NAV_ICON = LayoutIcon;

/**
 * Get an icon component by key
 */
export function getNavIcon(key?: string | null): React.FC {
  if (!key) return DEFAULT_NAV_ICON;
  return NAV_ICON_MAP[key] || DEFAULT_NAV_ICON;
}
